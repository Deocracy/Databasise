from __future__ import annotations

JOB_ID = "3f9c2a7e5b1d4c88a0e6f1d2c3b4a597"
LIMIT = 26_214_400
MSG_EMPTY_FILE = "The file is empty. Choose a file with content."
MSG_BIG_FILE = "The file is larger than 26,214,400 bytes."
MSG_ID = "Document id may contain only letters, digits, underscore and hyphen."
MSG_PAGE_SIZE = "Page size must be between 1 and 100."
DUP_ERROR = "Identical content already exists under another filename"


def _small_file(tmp_path, size: int = 10):
    path = tmp_path / f"small-{size}.txt"
    path.write_bytes(b"x" * size)
    return path


def _empty_file(tmp_path):
    path = tmp_path / "empty.txt"
    path.write_bytes(b"")
    return path


def _big_file(tmp_path):
    path = tmp_path / "big.bin"
    path.write_bytes(b"")
    with path.open("r+b") as handle:
        handle.truncate(LIMIT + 1)  # sparse: 26,214,401 bytes without writing them
    return path


def _upload_tab(ui) -> None:
    ui.show("documents")
    ui.el("documents.tabs.upload").click()


def _choose_capability(ui, tokens: list[str]) -> None:
    ui.el("documents.selector.kind-capability").check()
    ui.el("documents.selector.capability").select_option(tokens)


def _open_drawer(ui) -> None:
    ui.show("documents")
    ui.el("documents.jobs.open").click()
    ui.expect("documents.jobs.drawer").to_be_visible()


def _focused_id(ui) -> str | None:
    return ui.page.evaluate("() => document.activeElement && document.activeElement.getAttribute('data-mock-id')")


def _wait_focus(ui, mock_id: str) -> None:
    ui.page.wait_for_function(
        "(id) => document.activeElement && document.activeElement.getAttribute('data-mock-id') === id",
        arg=mock_id,
    )


def test_paste_submit_returns_a_job_card(ui):
    ui.show("documents")
    ui.el("documents.tabs.paste").click()
    ui.el("documents.paste.text").fill("The supplier contract renews on 1 March 2027.")
    ui.el("documents.paste.submit").click()
    ui.expect("documents.state.in-flight").to_be_visible()
    ui.expect("documents.paste.submit").to_be_disabled()

    ui.expect("documents.result.card").to_be_visible()
    ui.expect("documents.result.card").to_contain_text(JOB_ID)
    ui.el("documents.result.open-job").click()
    ui.expect("documents.jobs.drawer").to_be_visible()
    ui.expect("documents.jobs.documents").to_contain_text("contract-2026-q1")


def test_upload_size_prechecks(ui, tmp_path):
    _upload_tab(ui)
    for path, message in ((_empty_file(tmp_path), MSG_EMPTY_FILE), (_big_file(tmp_path), MSG_BIG_FILE)):
        ui.el("documents.upload.file").set_input_files(str(path))
        ui.expect("documents.upload.file-error").to_have_text(message)
        ui.expect("documents.upload.submit").to_be_disabled()
        ui.expect("documents.upload.progress").to_be_hidden()

    ui.el("documents.upload.file").set_input_files(str(_small_file(tmp_path)))
    ui.expect("documents.upload.file-error").to_be_hidden()
    ui.expect("documents.upload.submit").to_be_enabled()


def test_jobs_page_size_and_next(ui):
    _open_drawer(ui)
    ui.load("documents", "j-page1")
    ui.expect("documents.jobs.next").to_be_enabled()

    for bad in ("0", "101"):
        ui.el("documents.jobs.page-size").fill(bad)
        ui.expect("documents.jobs.page-size-error").to_have_text(MSG_PAGE_SIZE)
    ui.el("documents.jobs.page-size").fill("50")
    ui.expect("documents.jobs.page-size-error").to_be_hidden()

    ui.expect("documents.jobs.counts").to_contain_text("whole corpus, not this job")
    reason = ui.page.get_by_text(DUP_ERROR).filter(visible=True)
    ui.expect(reason).to_have_count(0)
    ui.el("documents.jobs.error-toggle-3").click()
    ui.expect(reason.first).to_be_visible()

    ui.load("documents", "j-last")
    ui.expect("documents.jobs.next").to_be_disabled()


def test_delete_is_offered_for_hipporag_selectors(ui):
    ui.show("documents")
