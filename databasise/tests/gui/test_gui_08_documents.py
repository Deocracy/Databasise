def test_gui_08_ingest_prechecks_jobs_and_delete(ui, tmp_path):
    # Paste tab: a document id with a space blocks Submit.
    ui.show("documents")
    ui.el("documents.tabs.paste").click()
    ui.el("documents.paste.text").fill("Some text")
    ui.el("documents.paste.document-id").fill("a b")
    ui.expect("documents.paste.document-id-error").to_have_text(MSG_ID)
    ui.expect("documents.paste.submit").to_be_disabled()

    # Upload tab: empty and oversize files are blocked.
    ui.el("documents.tabs.upload").click()
    ui.el("documents.upload.file").set_input_files(str(_empty_file(tmp_path)))
    ui.expect("documents.upload.file-error").to_have_text(MSG_EMPTY_FILE)
    ui.expect("documents.upload.submit").to_be_disabled()
    ui.el("documents.upload.file").set_input_files(str(_big_file(tmp_path)))
    ui.expect("documents.upload.file-error").to_have_text(MSG_BIG_FILE)
    ui.expect("documents.upload.submit").to_be_disabled()

    # Jobs drawer: page size bounds and the last page.
    _open_drawer(ui)
    ui.load("documents", "j-page1")
    for bad in ("0", "101"):
        ui.el("documents.jobs.page-size").fill(bad)
        ui.expect("documents.jobs.page-size-error").to_have_text(MSG_PAGE_SIZE)
    ui.el("documents.jobs.page-size").fill("50")
    ui.load("documents", "j-last")
    ui.expect("documents.jobs.next").to_be_disabled()
    ui.load("documents", "j-page1")

    # Default selector: the dialog names the document and Default; focus starts on Keep document.
    ui.el("documents.jobs.delete-1").click()
    dialog = ui.el("shell.dialog.delete")
    ui.expect(dialog).to_be_visible()
    ui.expect(dialog).to_contain_text("contract-2026-q1")
    ui.expect(dialog).to_contain_text("Default")
    _wait_focus(ui, "shell.dialog.delete-cancel")
    assert _focused_id(ui) == "shell.dialog.delete-cancel"
    ui.el("shell.dialog.delete-cancel").click()
    ui.expect(dialog).to_be_hidden()

    # HippoRAG-resolving selector: Delete is still offered and the dialog names the selector (D-08).
    ui.el("documents.jobs.close").click()
    _choose_capability(ui, ["reads_graph"])
    _open_drawer(ui)
    ui.load("documents", "j-page1")
    ui.expect("documents.jobs.delete-1").to_be_visible()
    ui.expect("documents.jobs.delete-1").to_be_enabled()
    ui.el("documents.jobs.delete-1").click()
    ui.expect(dialog).to_be_visible()
    ui.expect(dialog).to_contain_text("capability reads_graph")
