from __future__ import annotations

import re

STATES = [
    "idle",
    "running",
    "success",
    "partial",
    "empty-evidence",
    "refusal-422",
    "validation-422",
    "error-500",
]
ARMS = ["naive", "bypass", "hybrid", "local", "global", "hipporag"]
TEXT = "When does the supplier contract renew?"
HASH_LOWER = "0123456789abcdef" * 4
HASH_UPPER = "sha256:" + "0123456789ABCDEF" * 4

MSG_TEXT_EMPTY = "Query text is empty. Enter at least one non-space character."
MSG_NO_CAPABILITY = "Select at least one capability. An empty set is refused by the server."
MSG_NO_ALIAS = "Enter an alias, or choose Default."
MSG_HASH_ALIAS = (
    "This alias looks like a hash (64 hex characters, optional sha256: prefix). "
    "The server refuses it."
)
MSG_MULTI_MEMBER = "A selector may set only one member: alias, capability or harness."
MSG_BAD_JSON = "Raw selector JSON is not valid JSON."


def _visible_text(ui, text: str):
    """The first visible element carrying ``text`` anywhere on the page."""
    return ui.page.get_by_text(text).filter(visible=True).first


def _start(ui, text: str = TEXT) -> None:
    ui.show("query")
    ui.el("query.text.input").fill(text)


def _run(ui, text: str = TEXT) -> None:
    _start(ui, text)
    ui.el("query.run.submit").click()


def _column(ui, table_id: str, header: str):
    """Visible body cells under the column titled ``header`` of table ``table_id``."""
    table = ui.el(table_id)
    headers = [h.strip() for h in table.locator("thead th").all_inner_texts()]
    index = headers.index(header) + 1
    return table.locator("tbody tr:visible").locator(f"td:nth-child({index})")


