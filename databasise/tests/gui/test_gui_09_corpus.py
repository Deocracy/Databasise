def test_interrupted_tile_and_retry(ui):
    ui.show("corpus")
    ui.load("corpus", "counts-normal")
    ui.expect("corpus.kpi.preprocessed").to_be_hidden()
    ui.expect("corpus.kpi.interrupted").to_be_hidden()

    ui.load("corpus", "counts-preprocessed")
    ui.expect("corpus.kpi.preprocessed").to_be_visible()
    ui.expect("corpus.kpi.interrupted").to_be_visible()
    visible = [mock_id for mock_id in RETRY_IDS if ui.el(mock_id).is_visible()]
    assert len(visible) == 1, f"expected exactly one visible Retry button, found {visible}"
    ui.expect(visible[0]).to_have_text("Retry")
    ui.expect(visible[0]).to_be_enabled()
    _no_backend_ancestor(ui, visible[0])


def test_empty_corpus_links_to_paste_text(ui):
    ui.show("corpus")
    ui.load("corpus", "counts-empty")
    ui.expect("corpus.state.empty").to_contain_text("No LightRAG (v1) documents yet")
    ui.el("corpus.state.ingest-link").click()
    ui.expect("screen-documents").to_be_visible()
    ui.expect("documents.tabs.paste").to_have_attribute("aria-selected", "true")


def test_gui_09_health_tiles_and_corpus_table(ui):
    ui.show("corpus")
    ui.expect(ui.el("screen-corpus").locator("h1")).to_have_text("LightRAG (v1) documents")
    _check_degraded_health(ui)

    ui.load("corpus", "counts-normal")
    ui.expect("corpus.kpi.preprocessed").to_be_hidden()
    all_rows = _visible_statuses(ui)
    assert all_rows and all(status for status in all_rows), f"rows without data-status: {all_rows}"

    ui.el("corpus.kpi.failed").click()
    ui.expect("corpus.table.clear-filter").to_be_visible()
    failed_rows = _visible_statuses(ui)
    assert len(failed_rows) >= 2 and set(failed_rows) == {"failed"}, failed_rows
    assert len(failed_rows) < len(all_rows), "the failed filter must leave a proper subset"

    ui.el("corpus.kpi.total").click()
    ui.expect("corpus.table.clear-filter").to_be_hidden()
    assert _visible_statuses(ui) == all_rows

    ui.load("corpus", "counts-empty")
    ui.expect("corpus.state.empty").to_be_visible()
    ui.el("corpus.state.ingest-link").click()
    ui.expect("screen-documents").to_be_visible()
    ui.expect("documents.tabs.paste").to_have_attribute("aria-selected", "true")
