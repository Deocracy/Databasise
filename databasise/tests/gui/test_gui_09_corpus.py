"""17-05 (GUI-09; D-14): Corpus & Health screen of the operator console mockup.

Wave 0: written before the Corpus & Health markup exists (17-10 builds it); until then each node fails on
a missing ``corpus.*`` id or an unregistered ``window.__mock`` screen hook. D-14: ``clients`` and
``engine_reason`` are existing ``GET /health`` fields and carry no ``data-needs-backend`` wrapper or
badge, while store-busy (``corpus.health.busy``) sits in the operator-route wrapper ``GET /info``. The
overall badge reads ``stores openable / v1 reachable`` (never "healthy"); the vector key the server did not
report reads ``not probed``. Code drift pinned here: the ``interrupted`` status, its tile and the
single-document Retry (existing ``POST /documents/{document_id}/retry``, no badge). Fixtures: health
``health-ok|degraded|loading|error``; counts ``counts-normal|preprocessed|empty``. Every table body row
carries ``data-status``. Later plans do not edit this file."""

from __future__ import annotations

OVERALL = "stores openable / v1 reachable"
RETRY_IDS = [f"corpus.table.retry-{n}" for n in range(1, 7)]


def _no_backend_ancestor(ui, mock_id: str) -> None:
    ui.expect(ui.el(mock_id).locator("xpath=ancestor::*[@data-needs-backend]")).to_have_count(0)


def _visible_statuses(ui) -> list[str | None]:
    return ui.el("corpus.table.documents").evaluate(
        "t => Array.from(t.querySelectorAll('tbody tr:not([hidden])')).map(r => r.getAttribute('data-status'))"
    )


def _check_degraded_health(ui) -> None:
    ui.load("corpus", "health-degraded")
    ui.expect("corpus.health.overall").to_have_text(OVERALL)
    ui.expect("corpus.health.overall").to_have_attribute("data-state", "degraded")
    ui.expect("corpus.health.state").to_have_text("degraded")

    rows = ui.el("corpus.health.stores").locator("tbody tr")
    ui.expect(rows.filter(has_text="vector:chunks")).to_contain_text("not probed")
    absent = rows.filter(has_text="hipporag-")
    ui.expect(absent).to_have_count(5)
    for index in range(5):
        ui.expect(absent.nth(index)).to_contain_text("absent")

    ui.expect("corpus.health.engine").to_contain_text("v1 engine reachable")
    ui.expect("corpus.health.interpreter").to_contain_text("v1 interpreter present")


def test_health_panel_renders_degraded_fixture(ui):
    ui.show("corpus")
    _check_degraded_health(ui)


def test_clients_and_reasons_come_from_health(ui):
    ui.show("corpus")
    ui.load("corpus", "health-degraded")
    ui.expect("corpus.health.reasons").to_contain_text("model clients not configured")
    for client in ("llm", "embedding", "rerank"):
        ui.expect("corpus.health.clients").to_contain_text(client)
    _no_backend_ancestor(ui, "corpus.health.reasons")
    _no_backend_ancestor(ui, "corpus.health.clients")

    wrapper = ui.el("corpus.health.busy").locator('xpath=ancestor::*[@data-needs-backend="GET /info"]')
    ui.expect(wrapper).to_have_count(1)
    ui.expect(wrapper).to_have_attribute("data-backend-state", "operator")


