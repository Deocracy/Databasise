"""17-05 (GUI-11; D-05, D-10): Graph/vector browser screen of the operator console mockup.

Wave 0: written before the Graph markup exists (17-12 builds it); until then each node fails on a missing
``graph.*`` id or an unregistered ``window.__mock`` screen hook. D-05: node attributes load only through
``Load attributes``, inside the ``POST /graph/node/attrs`` needs-backend wrapper. D-10: every graph control
sits in a needs-backend wrapper; the screen has no namespace control and the chunk table no namespace
column (a chunk's Open still carries the ref into the Evidence Inspector). Fixtures: ``lightrag`` (default
on first show: node ``ACME CORP`` degree 12, 214 nodes, edges page 1 of 6 rows with ``next_offset`` 6 and
page 2 of 6 rows with ``next_offset`` null, chunk ``c-7f3a91``), ``hipporag``, ``store-busy``,
``unknown-node``. The two whole-screen walks assert presence first so they cannot pass on an empty
screen. Later plans do not edit this file."""

from __future__ import annotations

import re

NODE_PREFIXES = [
    "graph.selector.",
    "graph.counts.",
    "graph.nodes.",
    "graph.node.",
    "graph.edges.",
    "graph.chunks.",
]
WALK_ANCHORS = [
    "graph.selector.group",
    "graph.counts.nodes",
    "graph.nodes.table",
    "graph.node.attrs-load",
    "graph.edges.table",
    "graph.chunks.table",
]
NAMESPACE_JS = """root => {
  const re = /namespace/i;
  const bad = [];
  root.querySelectorAll('input,select,textarea,button').forEach(el => {
    const labels = Array.from(el.labels || []).map(l => l.textContent).join(' ');
    const attrs = ['name', 'id', 'data-mock-id', 'aria-label', 'placeholder']
      .map(a => el.getAttribute(a) || '').join(' ');
    const own = el.tagName === 'BUTTON' ? el.textContent : '';
    if (re.test(attrs + ' ' + labels + ' ' + own)) bad.push(el.getAttribute('data-mock-id') || el.tagName);
  });
  root.querySelectorAll('[data-mock-id="graph.chunks.table"] th').forEach(th => {
    if (re.test(th.textContent)) bad.push('th: ' + th.textContent.trim());
  });
  return bad;
}"""
UNWRAPPED_JS = """(prefixes) => {
  const matched = Array.from(document.querySelectorAll('[data-mock-id]'))
    .filter(el => prefixes.some(p => el.getAttribute('data-mock-id').startsWith(p)));
  return {
    total: matched.length,
    bare: matched.filter(el => !el.closest('[data-needs-backend]')).map(el => el.getAttribute('data-mock-id')),
  };
}"""


def _graph(ui) -> None:
    ui.nav("graph")
    ui.expect("screen-graph").to_be_visible()


def _open_acme(ui) -> None:
    _graph(ui)
    ui.el("graph.nodes.open-1").click()
    ui.expect("graph.node.panel").to_contain_text("ACME CORP")


def _assert_no_namespace_control(ui) -> None:
    for anchor in ("graph.nodes.table", "graph.chunks.table", "graph.selector.group"):
        ui.expect(anchor).to_be_visible()
    assert ui.el("screen-graph").evaluate(NAMESPACE_JS) == []


def test_node_list_and_detail(ui):
    _graph(ui)
    for slot in range(1, 9):
        ui.expect(f"graph.nodes.open-{slot}").to_be_visible()
    ui.expect("graph.nodes.total").to_contain_text("214")

    ui.el("graph.nodes.open-1").click()
    ui.expect("graph.node.panel").to_contain_text("ACME CORP")
    ui.expect("graph.node.degree").to_have_text(re.compile(r"\b12\b"))
    for slot in range(1, 7):
        ui.expect(f"graph.edges.open-{slot}").to_be_visible()
    ui.expect("graph.edges.next").to_be_enabled()
    ui.expect("graph.edges.table").to_contain_text("—")


def test_attributes_load_on_request(ui):
    _open_acme(ui)
    ui.expect("graph.node.attrs").to_be_hidden()
    wrapper = ui.el("graph.node.attrs-load").locator("xpath=ancestor::*[@data-needs-backend][1]")
    ui.expect(wrapper).to_have_attribute("data-needs-backend", "POST /graph/node/attrs")
    ui.expect(wrapper).to_contain_text("needs backend")

    ui.el("graph.node.attrs-load").click()
    ui.expect("graph.node.attrs").to_be_visible()
    ui.expect("graph.node.attrs").to_contain_text("entity_type")
    ui.expect("graph.node.attrs").to_contain_text("ORGANIZATION")


def test_chunk_open_uses_the_evidence_inspector(ui):
    _graph(ui)
    ui.el("graph.chunks.open-1").click()
    ui.expect("screen-evidence").to_be_visible()
    ui.expect("evidence.inspector.header").to_contain_text("c-7f3a91")


def test_no_namespace_control_on_the_screen(ui):
    _graph(ui)
    _assert_no_namespace_control(ui)


def test_every_graph_control_is_in_a_needs_backend_wrapper(ui):
    _graph(ui)
    for anchor in WALK_ANCHORS:
        ui.expect(anchor).to_be_attached()
    walk = ui.page.evaluate(UNWRAPPED_JS, NODE_PREFIXES)
    assert walk["total"] >= len(WALK_ANCHORS), walk
    assert walk["bare"] == [], f"graph controls outside a needs-backend wrapper: {walk['bare']}"


def test_store_busy_and_unknown_node_states(ui):
    _graph(ui)
    ui.load("graph", "store-busy")
    ui.expect("graph.state.store-busy").to_contain_text("store busy")
    ui.expect("graph.state.store-busy").to_contain_text("StoreBusyError")
    ui.expect("graph.state.retry").to_have_text("Retry request")

    ui.load("graph", "unknown-node")
    ui.expect(ui.el("graph.state.unknown-node").locator("mark")).to_have_text("UNKNOWN NODE")


def test_gui_11_graph_browser(ui):
    _graph(ui)
    _assert_no_namespace_control(ui)

    # Prefix filter leaves the two ACME rows.
    ui.el("graph.nodes.prefix").fill("AC")
    ui.expect("graph.nodes.open-1").to_be_visible()
    ui.expect("graph.nodes.open-2").to_be_visible()
    for slot in range(3, 9):
        ui.expect(f"graph.nodes.open-{slot}").to_be_hidden()
    ui.expect(ui.el("graph.nodes.open-1").locator("xpath=ancestor::tr[1]")).to_contain_text("ACME CORP")
    ui.expect(ui.el("graph.nodes.open-2").locator("xpath=ancestor::tr[1]")).to_contain_text("ACME HOLDINGS")

    # Node detail and edge paging.
    ui.el("graph.nodes.open-1").click()
    ui.expect("graph.node.panel").to_contain_text("ACME CORP")
    ui.expect("graph.edges.open-1").to_be_visible()
    ui.el("graph.edges.next").click()
    ui.expect("graph.edges.next").to_be_disabled()
    ui.expect("graph.edges.prev").to_be_enabled()

    # Chunk Open lands in the Evidence Inspector.
    _graph(ui)
    ui.el("graph.chunks.open-1").click()
    ui.expect("screen-evidence").to_be_visible()
    ui.expect("evidence.inspector.header").to_contain_text("c-7f3a91")

    # Store busy state.
    _graph(ui)
    ui.load("graph", "store-busy")
    ui.expect("graph.state.store-busy").to_contain_text("store busy")
