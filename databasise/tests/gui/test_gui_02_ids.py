"""17-01 (GUI-02; D-02): every control and region in the mockup carries a unique ``data-mock-id`` that
follows the grammar ``<screen>.<region>.<control>``, and the set equals ``docs/gui/MOCK-IDS.json``.
The id walk uses ``html.parser`` and must agree with ``scripts/mockup-id-check.py`` (regex) inside the
``console-a`` variant root, so a raw angle bracket in an attribute value or an unbalanced div fails here
before the freeze. Regenerate the list with ``DATABASISE_REGENERATE=1 databasise/.venv/bin/python -m
pytest -q databasise/tests/gui/test_gui_02_ids.py -p no:cacheprovider``. Later plans do not edit this file."""

from __future__ import annotations

import importlib.util
import json
import os
import re
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
IDS_FILE = ROOT / "docs" / "gui" / "MOCK-IDS.json"
CHECKER = ROOT / "scripts" / "mockup-id-check.py"
REGENERATE_HINT = (
    "regenerate with: DATABASISE_REGENERATE=1 databasise/.venv/bin/python -m pytest -q "
    "databasise/tests/gui/test_gui_02_ids.py -p no:cacheprovider"
)

# Controls and tables (17-UI-SPEC "Elements that must carry an id").
CONTROL_TAGS = {"button", "input", "select", "textarea", "a", "summary"}
NEED_TAGS = CONTROL_TAGS | {"table", "dialog"}
NEED_ROLES = {"tab", "dialog", "table", "status", "alert"}
# Regions: screen roots and panels are <section>; planned lists are <details> (D-03); the class
# names are defined by 17-02's mockups/src/css/00-base.css.
REGION_TAGS = {"section", "details"}
REGION_CLASSES = {"panel", "banner", "state-view", "badges"}

SEGMENT = r"[a-z0-9]+(?:-[a-z0-9]+)*"
SCREEN_ROOT = re.compile(r"^screen-(query|evidence|documents|corpus|ledger|graph)$")
THREE_SEGMENTS = re.compile(rf"^({SEGMENT})\.({SEGMENT})\.({SEGMENT})$")
FIRST_SEGMENTS = {"shell", "query", "evidence", "documents", "corpus", "ledger", "graph"}
STATE_ID = re.compile(rf"^{SEGMENT}\.state\.{SEGMENT}$")
BADGES_ID = re.compile(rf"^{SEGMENT}\.{SEGMENT}\.badges(?:-\d+)?$")


class Walk(HTMLParser):
    """Collects ids, the variant element, id-less elements that need one, and marker mismatches."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.ids: list[str] = []
        self.variant: dict | None = None
        self.missing: list[str] = []
        self.mismatches: list[str] = []

    def handle_starttag(self, tag, attrs):
        a = {k: (v or "") for k, v in attrs}
        classes = set(a.get("class", "").split())
        if "data-mock-variant" in a:
            self.variant = a
        mock_id = a.get("data-mock-id")
        if mock_id:
            self.ids.append(mock_id)
            if STATE_ID.match(mock_id) and tag not in CONTROL_TAGS and "state-view" not in classes:
                self.mismatches.append(f"{mock_id}: state view needs class state-view")
            if BADGES_ID.match(mock_id) and "badges" not in classes:
                self.mismatches.append(f"{mock_id}: badge group needs class badges")
            return
        if (
            tag in NEED_TAGS
            or tag in REGION_TAGS
            or a.get("role") in NEED_ROLES
            or classes & REGION_CLASSES
        ):
            self.missing.append(f"<{tag}> role={a.get('role', '')!r} class={a.get('class', '')!r}")


def _walk(text: str) -> Walk:
    walk = Walk()
    walk.feed(text)
    walk.close()
    return walk


def _checker():
    spec = importlib.util.spec_from_file_location("mockup_id_check", CHECKER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# One id-less element of each region kind, plus the two marker mismatches (nine reports in all).
_SAMPLE = """
<section hidden></section>
<section class="panel"></section>
<details></details>
<div role="alert"></div>
<div class="banner"></div>
<div class="state-view"></div>
<div class="badges"></div>
<div data-mock-id="query.state.idle"></div>
<div data-mock-id="query.result.badges"></div>
"""


def test_gui_02_every_control_has_a_unique_id_matching_the_checked_in_list(mockup_path: Path):
    probe = _walk(_SAMPLE)
    assert len(probe.missing) == 7, f"predicate must flag each region kind: {probe.missing}"
    assert len(probe.mismatches) == 2, probe.mismatches
    assert any("state view needs class state-view" in m for m in probe.mismatches)
    assert any("badge group needs class badges" in m for m in probe.mismatches)

    walk = _walk(mockup_path.read_text(encoding="utf-8"))
    assert walk.missing == [], f"elements without data-mock-id: {walk.missing}"
    assert walk.mismatches == [], f"marker mismatches: {walk.mismatches}"
    repeated = sorted(i for i, n in Counter(walk.ids).items() if n > 1)
    assert repeated == [], f"repeated data-mock-id values: {repeated}"
    assert walk.variant is not None, "no element carries data-mock-variant"
    assert walk.variant.get("data-mock-id") == "shell.root.app"
    assert walk.variant.get("data-mock-variant") == "console-a"

    ids = sorted(set(walk.ids))
    if os.environ.get("DATABASISE_REGENERATE") == "1":
        IDS_FILE.parent.mkdir(parents=True, exist_ok=True)
        IDS_FILE.write_text(json.dumps(ids, indent=2) + "\n", encoding="utf-8")

    assert IDS_FILE.is_file(), f"{IDS_FILE} is missing; {REGENERATE_HINT}"
    listed = json.loads(IDS_FILE.read_text(encoding="utf-8"))
    assert listed == sorted(listed), "docs/gui/MOCK-IDS.json is not sorted"
    assert len(listed) == len(set(listed)), "docs/gui/MOCK-IDS.json has duplicates"
    missing = sorted(set(ids) - set(listed))
    extra = sorted(set(listed) - set(ids))
    assert set(listed) == set(ids), (
        f"docs/gui/MOCK-IDS.json differs from the mockup: missing={missing} extra={extra}; "
        f"{REGENERATE_HINT}"
    )


def test_ids_follow_the_grammar(mockup_path: Path):
    bad = []
    for mock_id in _walk(mockup_path.read_text(encoding="utf-8")).ids:
        if SCREEN_ROOT.match(mock_id):
            continue
        match = THREE_SEGMENTS.match(mock_id)
        if not match or match.group(1) not in FIRST_SEGMENTS:
            bad.append(mock_id)
    assert bad == [], f"ids outside the grammar <screen>.<region>.<control>: {sorted(set(bad))}"


def test_parser_ids_equal_the_freeze_checker_ids(mockup_path: Path):
    checker = _checker()
    text = mockup_path.read_text(encoding="utf-8")
    spans = checker.variant_spans(text, "console-a")
    assert spans, "scripts/mockup-id-check.py finds no console-a variant element"
    regex_ids = checker.find_ids("\n".join(text[start:end] for start, end in spans))
    parser_ids = set(_walk(text).ids)
    assert regex_ids == parser_ids, (
        f"html.parser and mockup-id-check.py disagree: only parser={sorted(parser_ids - regex_ids)} "
        f"only checker={sorted(regex_ids - parser_ids)}"
    )
