"""17-01 (GUI-01; D-01, D-11, D-15): the mockup is one static file with six screens, a header health
indicator and nav, zero network requests, and inline fixtures. These tests are written before the
file exists (17-02 builds it) and fail on the missing-file assertion in ``mockup_path`` until then.
Later plans do not edit this file."""

from __future__ import annotations

import re
from pathlib import Path

SCREENS = [
    ("query", "Query & Compare"),
    ("evidence", "Evidence & Trace"),
    ("documents", "Documents & Jobs"),
    ("corpus", "Corpus & Health"),
    ("ledger", "Ledger"),
    ("graph", "Graph/vector browser"),
]
HEALTH_TEXT = "stores openable / v1 reachable"

# shortcut: regex scan of the source, not a DOM walk; upgrade if the file ever builds markup from strings.
_NETWORK_REFERENCES = {
    "<link": r"<link\b",
    "<script src": r"<script\b[^>]*\bsrc\s*=",
    "<img src": r"<img\b[^>]*\bsrc\s*=",
    "@import": r"@import",
    "url(http": r"url\(\s*['\"]?https?:",
}


def test_gui_01_six_screens_switch_with_header_health_and_no_requests(ui):
    for name, label in SCREENS:
        ui.expect(f"shell.nav.{name}").to_have_text(label)

    for name, _label in SCREENS:
        ui.nav(name)
        for other, _ in SCREENS:
            if other == name:
                ui.expect(f"screen-{other}").to_be_visible()
            else:
                ui.expect(f"screen-{other}").to_be_hidden()
        ui.expect(f"shell.nav.{name}").to_have_attribute("aria-current", "page")
        ui.page.wait_for_function(f"location.hash === '#{name}'")
        ui.expect("shell.health.status").to_be_visible()
        ui.expect("shell.health.status").to_contain_text(HEALTH_TEXT)

    assert ui.requests == []
    assert ui.errors == []
    fixtures = ui.page.evaluate(
        "() => JSON.parse(document.getElementById('mock-fixtures').textContent)"
    )
    assert isinstance(fixtures, dict)


def test_hash_route_opens_the_named_screen(ui):
    ui.page.goto(ui.page.url.split("#")[0] + "#ledger")
    ui.page.reload()
    ui.page.wait_for_function("typeof window.__mock === 'object'")
    for name, _label in SCREENS:
        if name == "ledger":
            ui.expect("screen-ledger").to_be_visible()
        else:
            ui.expect(f"screen-{name}").to_be_hidden()


def test_file_references_no_network_resource(mockup_path: Path):
    text = mockup_path.read_text(encoding="utf-8")
    found = [
        label
        for label, pattern in _NETWORK_REFERENCES.items()
        if re.search(pattern, text, re.IGNORECASE)
    ]
    assert found == [], f"{mockup_path} references network resources: {found}"


def test_nav_fits_375px_without_horizontal_scroll(ui):
    ui.resize(375, 800)
    for name, _label in SCREENS:
        ui.expect(f"shell.nav.{name}").to_be_visible()
    assert ui.no_horizontal_scroll()
