def test_gui_10_promote_preflight_and_timeline(ui):
    _timeline(ui)

    # Neither change_origin radio is preselected.
    ui.expect("ledger.promote.origin-human").not_to_be_checked()
    ui.expect("ledger.promote.origin-machine").not_to_be_checked()

    # A partial trace blocks.
    ui.el("ledger.promote.trace-3").check()
    ui.expect("ledger.promote.preflight").to_contain_text(MSG_PARTIAL)
    ui.expect("ledger.promote.submit").to_be_disabled()
    ui.el("ledger.promote.trace-3").uncheck()

    # A HippoRAG trace alone does not (D-07); alias rules still apply.
    ui.el("ledger.promote.trace-5").check()
    ui.el("ledger.promote.origin-human").check()
    ui.expect("ledger.promote.preflight").to_contain_text(MSG_NO_ALIAS)
    ui.expect("ledger.promote.submit").to_be_disabled()
    ui.el("ledger.promote.alias").fill(HASH_ALIAS)
    ui.expect("ledger.promote.preflight").to_contain_text(MSG_HASH_ALIAS)
    ui.expect("ledger.promote.submit").to_be_disabled()
    ui.el("ledger.promote.alias").fill("staging")
    _no_blockers(ui)
    ui.expect("ledger.promote.submit").to_be_enabled()

    # The promote dialog states what Promote does.
    ui.el("ledger.promote.submit").click()
    ui.expect("shell.dialog.promote").to_be_visible()
    ui.expect("shell.dialog.promote").to_contain_text(PROMOTE_BODY)
    ui.el("shell.dialog.promote-cancel").click()
    ui.expect("shell.dialog.promote").to_be_hidden()

    # Timeline: Retire rules, and the typed version.
    _check_retire_rules(ui)
    ui.el("ledger.timeline.retire-3").click()
    ui.expect("shell.dialog.retire").to_be_visible()
    ui.expect("shell.dialog.retire-confirm").to_be_disabled()
    ui.el("shell.dialog.retire-version").fill("3.0")
    ui.expect("shell.dialog.retire-confirm").to_be_disabled()
