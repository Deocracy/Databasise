"""17-05 (GUI-10; D-07): Ledger screen of the operator console mockup.

Wave 0: written before the Ledger markup exists (17-11 builds it); until then each node fails on a missing
``ledger.*`` or ``shell.dialog.*`` id or an unregistered ``window.__mock`` screen hook. D-07: a HippoRAG
trace is NOT a pre-flight blocker (its chip is information only) while a partial trace is. Promote-form
trace slots, in fixture order: ``trace-1`` and ``trace-2`` complete naive (Default), ``trace-3`` partial
local, ``trace-4`` complete local, ``trace-5`` HippoRAG (``capability reads_graph+calls_llm``),
``trace-6`` complete naive (``alias prod``). Fixture ``timeline-prod`` (alias ``prod``) rows: 1 promotion
1.0.0 (target of the active rollback), 2 promotion 2.0.0 (tombstoned), 3 promotion 3.0.0, 4 tombstone,
5 rollback 4.0.0 (active). Retire sits in a ``<span title>`` wrapper. Later plans do not edit this file."""

from __future__ import annotations

HASH_ALIAS = "0123456789abcdef" * 4
BLOCKERS = [
    "Select at least one trace.",
    "Choose a change origin.",
    "Enter an alias.",
    "cannot be promoted",
    "cannot be used",
]
MSG_PARTIAL = "is a partial run and cannot be promoted."
MSG_NO_ALIAS = "Enter an alias."
MSG_HASH_ALIAS = (
    "This alias looks like a hash (64 hex characters, optional sha256: prefix) and cannot be used."
)
TIP_TARGET = "This version is the target of the active rollback. roll back first."
TIP_ACTIVE = "The active generation cannot be retired."
TIP_RETIRED = "This version is already retired."
PROMOTE_BODY = "repoints the alias; append-only; undo only by a later rollback"


def _timeline(ui) -> None:
    ui.show("ledger")
    ui.load("ledger", "timeline-prod")


def _retire_title(ui, slot: int):
    return ui.el(f"ledger.timeline.retire-{slot}").locator("xpath=ancestor::span[@title][1]")


def _no_blockers(ui) -> None:
    for blocker in BLOCKERS:
        ui.expect("ledger.promote.preflight").not_to_contain_text(blocker)


def _check_retire_rules(ui) -> None:
    for slot in (1, 2, 5):
        ui.expect(f"ledger.timeline.retire-{slot}").to_be_disabled()
    ui.expect("ledger.timeline.retire-3").to_be_enabled()


def test_timeline_renders_actions_per_row(ui):
    _timeline(ui)
    _check_retire_rules(ui)
    ui.expect("ledger.timeline.retire-4").to_be_hidden()
    ui.expect("ledger.timeline.rollback-4").to_be_hidden()
    for slot in (1, 3):
        ui.expect(f"ledger.timeline.rollback-{slot}").to_be_enabled()
    for slot in (2, 5):
        ui.expect(f"ledger.timeline.rollback-{slot}").to_be_disabled()

    ui.expect(_retire_title(ui, 1)).to_have_attribute("title", TIP_TARGET)
    ui.expect(_retire_title(ui, 5)).to_have_attribute("title", TIP_ACTIVE)
    ui.expect(_retire_title(ui, 2)).to_have_attribute("title", TIP_RETIRED)

    for status in ("target of active rollback", "tombstoned", "active"):
        ui.expect("ledger.timeline.table").to_contain_text(status)


def test_hipporag_trace_is_not_blocked(ui):
    _timeline(ui)
    ui.el("ledger.promote.alias").fill("staging")
    ui.el("ledger.promote.origin-human").check()
    ui.el("ledger.promote.trace-5").check()
    _no_blockers(ui)
    ui.expect("ledger.promote.preflight").not_to_contain_text("HippoRAG run")
    ui.expect("ledger.promote.submit").to_be_enabled()


def test_verb_select_offers_one_enabled_verb(ui):
    ui.show("ledger")
    verb = ui.el("ledger.promote.verb")
    ui.expect(verb.locator("option")).to_have_count(6)
    options = verb.evaluate(
        "s => Array.from(s.options).map((o, i) => ({value: o.value, text: o.textContent,"
        " disabled: o.disabled, selected: i === s.selectedIndex}))"
    )
    selected = [o for o in options if o["selected"]]
    assert len(selected) == 1 and selected[0]["value"] == "operator-asserted", options
    assert not selected[0]["disabled"], options
    others = [o for o in options if o["value"] != "operator-asserted"]
    assert len(others) == 5, options
    for option in others:
        assert option["disabled"], option
        assert "not built / gated" in option["text"], option


def test_retire_needs_the_typed_version(ui):
    _timeline(ui)
    ui.el("ledger.timeline.retire-3").click()
    ui.expect("shell.dialog.retire").to_be_visible()
    ui.expect("shell.dialog.retire-confirm").to_be_disabled()
    ui.el("shell.dialog.retire-version").fill("3.0")
    ui.expect("shell.dialog.retire-confirm").to_be_disabled()
    ui.el("shell.dialog.retire-version").fill("3.0.0")
    ui.el("shell.dialog.retire-traces").select_option(index=0)
    ui.el("shell.dialog.retire-origin-human").check()
    ui.expect("shell.dialog.retire-confirm").to_be_enabled()


