"""17-04 (GUI-06; D-04, D-09): the four server error shapes and the refusal catalogue.

Wave 0: written before any screen renders an error component (17-06 and the later screen plans build
them); the browser nodes fail on a missing ``<screen>.error.*`` id or an unregistered ``window.__mock``
screen until then. D-04 and D-09: the catalogue embedded in the mockup, ``docs/gui/refusals.json`` and the
runtime ``SeamRefusalError`` subclasses are the same set, compared by name with no hard-coded count. The
catalogue node passes now because the 17-02 build already embeds the catalogue. Branching is on
``refusal_type``, never on the status alone. Later plans do not edit this file."""

from __future__ import annotations

import json
from html.parser import HTMLParser
from pathlib import Path

import pytest

SCREENS = ["query", "evidence", "documents", "corpus", "ledger", "graph"]
SHAPES = ["refusal", "server-failure", "validation", "generic"]

REFUSAL = {
    "refusal_type": "UnknownTraceReferenceError",
    "message": "unknown trace reference",
    "trace_reference": "tok-abc123",
}
FOREIGN = {
    "refusal_type": "ForeignEngineRefusalError",
    "message": "operation 'query' failed (StoreFault)",
    "operation": "query",
    "failure_class": "StoreFault",
    "cause": "boom-cause",
}
VALIDATION = {"detail": [{"loc": ["body", "nonexistent"], "msg": "x", "type": "value_error"}]}


def _runtime_refusal_names() -> set[str]:
    # Importing these modules registers every runtime subclass of SeamRefusalError.
    from databasise.seam import evidence, refusals, tokens, trace_store  # noqa: F401

    found: set[type] = set()
    frontier = list(refusals.SeamRefusalError.__subclasses__())
    while frontier:
        cls = frontier.pop()
        if cls not in found:
            found.add(cls)
            frontier.extend(cls.__subclasses__())
    return {cls.__name__ for cls in found if not cls.__module__.startswith("databasise.tests")}


class _FixtureScript(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self._inside = False
        self.text = ""

    def handle_starttag(self, tag, attrs):
        self._inside = tag == "script" and ("id", "mock-fixtures") in attrs

    def handle_endtag(self, tag):
        if tag == "script":
            self._inside = False

    def handle_data(self, data):
        if self._inside:
            self.text += data


def _embedded_refusal_names(mockup_path: Path) -> set[str]:
    parser = _FixtureScript()
    parser.feed(mockup_path.read_text(encoding="utf-8"))
    return {entry["refusal_type"] for entry in json.loads(parser.text)["refusals"]}


def _file_refusal_names(mockup_path: Path) -> set[str]:
    path = mockup_path.parents[1] / "docs" / "gui" / "refusals.json"
    return {entry["refusal_type"] for entry in json.loads(path.read_text(encoding="utf-8"))}


def _assert_catalogue_matches(mockup_path: Path) -> None:
    runtime = _runtime_refusal_names()
    assert runtime, "no SeamRefusalError subclasses were found"
    assert _file_refusal_names(mockup_path) == runtime
    assert _embedded_refusal_names(mockup_path) == runtime


def _only(ui, screen: str, shape: str) -> None:
    ui.expect(f"{screen}.error.{shape}").to_be_visible()
    for other in SHAPES:
        if other != shape:
            ui.expect(f"{screen}.error.{other}").to_be_hidden()


def test_refusal_catalogue_matches_the_code_and_the_mockup(mockup_path):
    _assert_catalogue_matches(mockup_path)


@pytest.mark.parametrize("screen", SCREENS)
def test_every_screen_renders_the_four_shapes(ui, screen):
    ui.show(screen)

    ui.inject(screen, 422, REFUSAL)
    _only(ui, screen, "refusal")

    ui.inject(screen, 502, FOREIGN)
    _only(ui, screen, "server-failure")

    ui.inject(screen, 422, VALIDATION)
    _only(ui, screen, "validation")
    ui.expect(f"{screen}.error.validation").to_contain_text("The request has 1 invalid field(s).")

    ui.inject(screen, 500, "Internal Server Error")
    _only(ui, screen, "generic")
    ui.expect(f"{screen}.error.generic").to_contain_text("HTTP 500")


def test_branching_is_on_refusal_type_not_status(ui):
    ui.show("query")
    cases = [
        # A refusal_type wins over a detail array on the same 422.
        (422, {**REFUSAL, **VALIDATION}, "refusal"),
        (404, {"refusal_type": "UnknownJobError", "message": "unknown job", "job_id": "j1"}, "refusal"),
        (502, FOREIGN, "server-failure"),
        (422, VALIDATION, "validation"),
        (503, {}, "generic"),
    ]
    for status, body, shape in cases:
        ui.inject("query", status, body)
        _only(ui, "query", shape)

    ui.inject("query", 0, "")
    _only(ui, "query", "generic")
    ui.expect("query.error.generic").to_contain_text("No response from the server.")


def test_gui_06_four_error_shapes_and_catalogue(ui, mockup_path):
    _assert_catalogue_matches(mockup_path)

    field_errors = {"query": ("body.selector", "query.selector.error"),
                    "ledger": ("body.alias", "ledger.promote.alias-error")}
    for screen, (loc, error_id) in field_errors.items():
        ui.show(screen)

        ui.inject(screen, 422, REFUSAL)
        banner = ui.el(f"{screen}.error.refusal")
        ui.expect(banner).to_contain_text("UnknownTraceReferenceError")
        ui.expect(banner.locator("mark")).to_have_text("tok-abc123")
        ui.expect(f"{screen}.error.catalogue-link").to_have_text("Show in refusal catalogue")

        ui.inject(screen, 502, FOREIGN)
        cause = ui.page.get_by_text("boom-cause").filter(visible=True)
        toggle = ui.el(f"{screen}.error.details-toggle")
        ui.expect(toggle).to_have_text("Show details")
        ui.expect(toggle).to_have_attribute("aria-expanded", "false")
        ui.expect(cause).to_have_count(0)
        toggle.click()
        ui.expect(toggle).to_have_attribute("aria-expanded", "true")
        ui.expect(cause.first).to_be_visible()
        ui.expect(toggle).to_have_text("Hide details")

        ui.inject(screen, 422, {"detail": [{"loc": loc.split("."), "msg": "field-msg-from-server",
                                            "type": "value_error"}]})
        field = ui.el(f"screen-{screen}").locator(f'[data-field-loc="{loc}"]')
        ui.expect(field).to_have_attribute("aria-invalid", "true")
        ui.expect(error_id).to_contain_text("field-msg-from-server")

        ui.inject(screen, 500, "Internal Server Error")
        ui.expect(f"{screen}.error.generic").to_contain_text("HTTP 500")
        ui.expect(f"{screen}.error.generic").to_contain_text("Internal Server Error")
