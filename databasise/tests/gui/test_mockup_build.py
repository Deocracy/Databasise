"""17-01 (GUI-01, GUI-02): the checked-in mockup is exactly what ``mockups/build.py`` assembles from
``mockups/src/``, so the single file never drifts from its partials. ``build.py`` is loaded inside the
test, never at module level, so the missing-file failure comes first. Later plans do not edit this file."""

from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BUILD = ROOT / "mockups" / "build.py"


def test_checked_in_mockup_equals_a_fresh_build(mockup_path: Path):
    assert BUILD.is_file(), f"{BUILD} is missing (mockup assembler not built yet)"
    spec = importlib.util.spec_from_file_location("mockup_build", BUILD)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert module.build() == mockup_path.read_text(encoding="utf-8"), (
        f"{mockup_path} differs from a fresh build; rebuild with: "
        "databasise/.venv/bin/python mockups/build.py"
    )
