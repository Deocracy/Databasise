"""17-04 (GUI-05; D-06, D-07): Compare mode of the operator console mockup.

Wave 0: written before the compare markup exists (17-07 builds it); every node fails on a missing
``query.compare.*``, ``query.rowN.*`` or ``query.colN.*`` id until then. D-06: hybrid and global are
offered as columns. D-07: a HippoRAG column can be promoted; only a partial column cannot. Rows are
built with a ``<select>`` ``query.rowN.kind`` whose options are labelled Default, Alias, Capability
and Harness. Later plans do not edit this file."""

from __future__ import annotations

TEXT = "When does the supplier contract renew?"
MSG_ONE_ROW = "One selector runs as a plain query and returns a single result, not a set of columns."
MSG_ZERO_ROWS = "Add at least one selector. A comparison with no selectors is refused."
CAP_NOTE = "The mockup shows up to 4 columns."
ENTITIES = "reads_vector:entities"
RELATIONSHIPS = "reads_vector:relationships"


def _duplicate(key: str) -> str:
    return f'Duplicate comparison key "{key}"'


def _open_compare(ui) -> None:
    ui.show("query")
    ui.el("query.mode.compare").click()
    ui.el("query.text.input").fill(TEXT)


def _set_alias(ui, row: int, alias: str) -> None:
    ui.el(f"query.row{row}.kind").select_option(label="Alias")
    ui.el(f"query.row{row}.alias").fill(alias)


def _set_capability(ui, row: int, tokens: list[str]) -> None:
    ui.el(f"query.row{row}.kind").select_option(label="Capability")
    ui.el(f"query.row{row}.capability").select_option(tokens)


def _visible_text(ui, text: str):
    return ui.page.get_by_text(text).filter(visible=True).first


def test_gui_05_compare_keys_columns_and_narrow_tabs(ui):
    _open_compare(ui)

    # Alias "default" collides with the Default row; the warning disables Run until the row is removed.
    _set_alias(ui, 1, "default")
    ui.el("query.compare.add").click()
    ui.expect("query.compare.warning-duplicate").to_contain_text(_duplicate("default"))
    ui.expect("query.run.submit").to_be_disabled()
    ui.el("query.row2.remove").click()
    ui.expect("query.compare.warning-duplicate").to_be_hidden()
    ui.expect("query.run.submit").to_be_enabled()

    # Three columns: the middle one is the only partial column and the only one that cannot be promoted.
    ui.load("query", "cmp-3col")
    for column in (1, 2, 3):
        ui.expect(f"query.col{column}.panel").to_be_visible()
    ui.expect("query.col4.panel").to_be_hidden()
    ui.expect("query.col2.state-partial").to_be_visible()
    ui.expect("query.col1.state-partial").to_be_hidden()
    ui.expect("query.col3.state-partial").to_be_hidden()
    ui.expect("query.col2.promote").to_be_disabled()
    ui.expect("query.col1.promote").to_be_enabled()
    ui.expect("query.col3.promote").to_be_enabled()

    # Below 768 px the columns become tabs and the page does not scroll sideways.
    ui.resize(375, 800)
    ui.expect("query.compare.tabs").to_be_visible()
    for tab in (1, 2, 3):
        ui.expect(f"query.compare.tab{tab}").to_be_visible()
    ui.expect("query.compare.tab4").to_be_hidden()
    ui.expect("query.compare.tab1").to_be_visible()
    assert sum(ui.el(f"query.col{c}.panel").is_visible() for c in (1, 2, 3, 4)) == 1
    ui.el("query.compare.tab2").click()
    ui.expect("query.col2.panel").to_be_visible()
    for other in (1, 3, 4):
        ui.expect(f"query.col{other}.panel").to_be_hidden()
    assert ui.no_horizontal_scroll()


def test_row_keys_preview_and_cross_kind_collision(ui):
    _open_compare(ui)
    ui.expect("query.row1.key").to_have_text("Key: default")
    _set_capability(ui, 1, [ENTITIES])
    ui.expect("query.row1.key").to_have_text(f"Key: {ENTITIES}")

    # An alias spelled like a joined capability set collides with that capability set.
    key = "reads_kv+calls_llm"
    _set_alias(ui, 1, key)
    ui.el("query.compare.add").click()
    _set_capability(ui, 2, ["reads_kv", "calls_llm"])
    ui.expect("query.row2.key").to_have_text(f"Key: {key}")
    ui.expect("query.compare.warning-duplicate").to_contain_text(_duplicate(key))
    ui.expect("query.row2.error").to_contain_text(_duplicate(key))


def test_zero_and_one_row_messages(ui):
    _open_compare(ui)
    ui.expect("query.compare.warning-count").to_contain_text(MSG_ONE_ROW)
    ui.expect("query.run.submit").to_be_enabled()

    ui.el("query.row1.remove").click()
    ui.expect("query.compare.warning-count").to_contain_text(MSG_ZERO_ROWS)
    ui.expect("query.run.submit").to_be_disabled()


def test_rows_reorder_and_cap_at_four(ui):
    _open_compare(ui)
    for row, alias in ((2, "a"), (3, "b"), (4, "c")):
        ui.el("query.compare.add").click()
        _set_alias(ui, row, alias)
    ui.expect("query.compare.add").to_be_disabled()
    ui.expect(_visible_text(ui, CAP_NOTE)).to_be_visible()

    ui.expect("query.row1.key").to_have_text("Key: default")
    ui.expect("query.row2.key").to_have_text("Key: a")
    ui.el("query.row2.move-up").click()
    ui.expect("query.row1.key").to_have_text("Key: a")
    ui.expect("query.row2.key").to_have_text("Key: default")

    for row in (1, 2, 3, 4):
        ui.expect(f"query.row{row}.move-up").to_have_attribute("aria-label", "Move selector up")
        ui.expect(f"query.row{row}.move-down").to_have_attribute("aria-label", "Move selector down")
        ui.expect(f"query.row{row}.remove").to_have_attribute("aria-label", "Remove selector")


def test_hipporag_column_is_promotable(ui):
    ui.show("query")
    ui.load("query", "cmp-3col")
    ui.expect("query.col3.resolves-to").to_contain_text("hipporag")
    ui.expect("query.col3.promote").to_be_enabled()
    ui.el("query.col3.promote").click()
    ui.expect("screen-ledger").to_be_visible()


def test_hybrid_and_global_are_offered_as_columns(ui):
    _open_compare(ui)
    _set_capability(ui, 1, [ENTITIES, RELATIONSHIPS])
    ui.el("query.compare.add").click()
    _set_capability(ui, 2, [RELATIONSHIPS])
    ui.expect("query.run.submit").to_be_enabled()
    ui.el("query.run.submit").click()
    ui.expect("query.state.running").to_be_visible()
    ui.expect("query.col1.resolves-to").to_contain_text("hybrid")
    ui.expect("query.col2.resolves-to").to_contain_text("global")
